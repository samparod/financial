export function tr(lang: Lang, key: string, vars?: TVars) {
  let s = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
  }
  return s;
}
